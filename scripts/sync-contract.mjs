#!/usr/bin/env node
/**
 * Sync packages/schema/contract/ctw-contract.json → TS constants + PHP Package_Contract.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contractPath = join(root, "packages/schema/contract/ctw-contract.json");
const contract = JSON.parse(readFileSync(contractPath, "utf8"));

assertList(contract.freeWidgets, "freeWidgets");
assertList(contract.corePlugins, "corePlugins");
assertList(contract.snippetTypes, "snippetTypes");
if (typeof contract.wooPlugin !== "string" || contract.wooPlugin === "") {
  throw new Error("wooPlugin must be a non-empty string");
}
if (!contract.pluginMains || typeof contract.pluginMains !== "object") {
  throw new Error("pluginMains must be an object");
}

const tsOut = join(root, "packages/schema/src/constants.ts");
const phpDir = join(root, "plugin/includes/contract");
const phpOut = join(phpDir, "class-package-contract.php");

mkdirSync(phpDir, { recursive: true });
writeFileSync(tsOut, renderTs(contract), "utf8");
writeFileSync(phpOut, renderPhp(contract), "utf8");
console.log(`Synced contract → ${tsOut}`);
console.log(`Synced contract → ${phpOut}`);

/**
 * @param {unknown} value
 * @param {string} name
 */
function assertList(value, name) {
  if (!Array.isArray(value) || value.length === 0 || !value.every((x) => typeof x === "string")) {
    throw new Error(`${name} must be a non-empty string array`);
  }
}

/**
 * @param {{ freeWidgets: string[]; corePlugins: string[]; wooPlugin: string; snippetTypes: string[]; pluginMains: Record<string, string> }} c
 */
function renderTs(c) {
  const widgets = c.freeWidgets.map((w) => `  ${JSON.stringify(w)},`).join("\n");
  const cores = c.corePlugins.map((w) => `  ${JSON.stringify(w)},`).join("\n");
  const snippets = c.snippetTypes.map((w) => `  ${JSON.stringify(w)},`).join("\n");
  return `/**
 * Package contract constants.
 *
 * AUTO-GENERATED by scripts/sync-contract.mjs — do not edit by hand.
 * Source: packages/schema/contract/ctw-contract.json
 */

/**
 * Free Elementor widget types allowed in ctw-package page trees.
 */
export const FREE_WIDGET_TYPES = [
${widgets}
] as const;

export type FreeWidgetType = (typeof FREE_WIDGET_TYPES)[number];

export const FREE_WIDGET_SET: ReadonlySet<string> = new Set(FREE_WIDGET_TYPES);

export const CORE_PLUGIN_SLUGS = [
${cores}
] as const;

export const WOO_PLUGIN_SLUG = ${JSON.stringify(c.wooPlugin)} as const;

export const SNIPPET_TYPES = [
${snippets}
] as const;

export type SnippetType = (typeof SNIPPET_TYPES)[number];
`;
}

/**
 * @param {{ freeWidgets: string[]; corePlugins: string[]; wooPlugin: string; snippetTypes: string[]; pluginMains: Record<string, string> }} c
 */
function renderPhp(c) {
  const widgets = c.freeWidgets.map((w) => `\t\t'${escapePhp(w)}',`).join("\n");
  const cores = c.corePlugins.map((w) => `\t\t'${escapePhp(w)}',`).join("\n");
  const snippets = c.snippetTypes.map((w) => `\t\t'${escapePhp(w)}',`).join("\n");
  const mains = Object.entries(c.pluginMains)
    .map(([slug, main]) => `\t\t'${escapePhp(slug)}' => '${escapePhp(main)}',`)
    .join("\n");

  return `<?php
/**
 * Shared package contract (generated from ctw-contract.json).
 *
 * AUTO-GENERATED by scripts/sync-contract.mjs — do not edit by hand.
 * Source: packages/schema/contract/ctw-contract.json
 *
 * @package CTW_Native
 */

namespace CTW_Native\\Contract;

if ( ! defined( 'ABSPATH' ) ) {
\texit;
}

/**
 * Single source for Free widgets, core plugins, snippets, and installer mains.
 */
final class Package_Contract {

\t/**
\t * @var list<string>
\t */
\tprivate const FREE_WIDGETS = array(
${widgets}
\t);

\t/**
\t * @var list<string>
\t */
\tprivate const CORE_PLUGINS = array(
${cores}
\t);

\tpublic const WOO_PLUGIN = '${escapePhp(c.wooPlugin)}';

\t/**
\t * @var list<string>
\t */
\tprivate const SNIPPET_TYPES = array(
${snippets}
\t);

\t/**
\t * @var array<string,string>
\t */
\tprivate const PLUGIN_MAINS = array(
${mains}
\t);

\t/**
\t * @return list<string>
\t */
\tpublic static function free_widgets(): array {
\t\treturn self::FREE_WIDGETS;
\t}

\t/**
\t * @param string $widget_type Widget type slug.
\t */
\tpublic static function is_free_widget( string $widget_type ): bool {
\t\treturn in_array( $widget_type, self::FREE_WIDGETS, true );
\t}

\t/**
\t * @return list<string>
\t */
\tpublic static function core_plugins(): array {
\t\treturn self::CORE_PLUGINS;
\t}

\t/**
\t * Declared plugin slugs for a package (core + optional Woo).
\t *
\t * @param bool $woo_enabled Whether woocommerce.enabled is true.
\t * @return list<string>
\t */
\tpublic static function declared_plugins( bool $woo_enabled ): array {
\t\t$plugins = self::CORE_PLUGINS;
\t\tif ( $woo_enabled ) {
\t\t\t$plugins[] = self::WOO_PLUGIN;
\t\t}
\t\treturn $plugins;
\t}

\t/**
\t * @return list<string>
\t */
\tpublic static function snippet_types(): array {
\t\treturn self::SNIPPET_TYPES;
\t}

\t/**
\t * @param string $type Snippet type.
\t */
\tpublic static function is_snippet_type( string $type ): bool {
\t\treturn in_array( $type, self::SNIPPET_TYPES, true );
\t}

\t/**
\t * @return array<string,string>
\t */
\tpublic static function plugin_mains(): array {
\t\treturn self::PLUGIN_MAINS;
\t}

\t/**
\t * @param string $slug Plugin slug.
\t */
\tpublic static function plugin_main( string $slug ): string {
\t\treturn self::PLUGIN_MAINS[ $slug ] ?? '';
\t}
}
`;
}

/** @param {string} value */
function escapePhp(value) {
  return value.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}
